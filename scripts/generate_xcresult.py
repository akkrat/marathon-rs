#!/usr/bin/env python3
"""Port of buildSrc/src/main/kotlin/com/malinskiy/marathon/buildsystem/Xcresulttool{,SourceCreator}.kt
and buildsystem/xcresulttool/{Property,Schema,Type,TypeDefinition,Version}.kt.

Generate only the owned generated.rs file from the checked-in schema; --check never writes.
Usage: python3 -I scripts/generate_xcresult.py [--check]
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / 'fixtures/xcresult/schema-3.39.json'
OUTPUT = ROOT / 'crates/marathon-apple/src/xcresult/generated.rs'
WKT = {'String': 'String', 'Int': 'i32', 'Double': 'f64', 'Bool': 'bool', 'Date': 'JavaDate'}


def included(prop):
    return prop['type'] != 'SchemaSerializable' and not prop.get('isInternal', False)


def unwrapped(prop):
    return prop['wrappedType'] if prop['isOptional'] or prop['type'] == 'Array' else prop['type']


def resolve(schema):
    for definition in schema['types']:
        if definition['kind'] not in ('object', 'value', 'array'):
            raise ValueError('Unknown xcresulttool type kind ' + definition['kind'])
    objects = [d for d in schema['types'] if d['kind'] == 'object']
    if len({d['type']['name'] for d in objects}) != len(objects):
        raise ValueError('Duplicate object type')
    done = {}
    while objects:
        ready = []
        for definition in objects:
            name = definition['type']['name']
            dependencies = [unwrapped(p) for p in definition['properties'] if included(p)]
            if definition['type'].get('supertype'):
                dependencies.append(definition['type']['supertype'])
            if all(d in done or d in WKT or d == 'Reference' or d == name for d in dependencies):
                ready.append(definition)
        if not ready:
            raise ValueError("Can't resolve types " + ', '.join(d['type']['name'] for d in objects))
        for definition in ready:
            name = definition['type']['name']
            fields = [dict(p) for p in definition['properties'] if included(p)]
            parent = definition['type'].get('supertype')
            if parent:
                if parent not in done:
                    raise ValueError('Unresolved superclass ' + parent)
                fields += done[parent]
            done[name] = fields
        objects = [d for d in objects if d not in ready]
    # Reference is artificial only for dependency resolution, never silently omitted.
    for name, fields in done.items():
        for prop in fields:
            target = unwrapped(prop)
            if target not in WKT and target not in done:
                raise ValueError('Unresolved property type ' + target)
    return done


def snake(name):
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    name = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).lower()
    return 'r#' + name if name in ('type', 'ref', 'self', 'match') else name


def rust_type(owner, prop):
    target = unwrapped(prop)
    value = WKT.get(target, target)
    if prop['type'] == 'Array':
        value = 'Vec<Option<' + value + '>>'
    elif target == owner:
        value = 'Box<' + value + '>'
    return 'Option<' + value + '>' if prop['isOptional'] else value


def render(schema, digest):
    objects = resolve(schema)
    version = schema['version']
    lines = [
        '//! Port of buildSrc/src/main/kotlin/com/malinskiy/marathon/buildsystem/XcresulttoolSourceCreator.kt',
        '//! Generated by scripts/generate_xcresult.py; do not edit.',
        f'//! Schema {version["major"]}.{version["minor"]}, signature {schema["signature"]}; fixtures/xcresult/schema-3.39.json.',
        f'//! Schema SHA-256: {digest}.',
        '', 'use super::decoder::{Decode, Fields, JsonNode, Path, XcresultDecodeError};',
        'use jcompat::jackson::JavaDate;', '',
        f'pub const OBJECT_TYPE_COUNT: usize = {len(objects)};', '',
    ]
    for name, fields in objects.items():
        lines += ['#[derive(Clone, Debug, PartialEq)]', f'pub struct {name} {{']
        for prop in fields:
            lines += [f'    pub {snake(prop["name"])}: {rust_type(name, prop)},']
        lines += ['}', '', f'impl Decode for {name} {{',
                  '    fn decode(node: &JsonNode, path: &Path) -> Result<Option<Self>, XcresultDecodeError> {',
                  '        if node.is_null() { return Ok(None); }',
                  '        let fields = Fields::new(node, path)?;', '        Ok(Some(Self {']
        for prop in fields:
            target = unwrapped(prop)
            if prop['type'] == 'Array':
                helper = 'optional_list' if prop['isOptional'] else 'list'
            elif prop['isOptional']:
                helper = 'optional'
            elif target in ('String', 'Int', 'Double', 'Bool'):
                helper = 'defaulted'
            else:
                helper = 'required'
            lines += [f'            {snake(prop["name"])}: fields.{helper}("{prop["name"]}")?,']
        lines += ['        }))', '    }', '}', '', '#[cfg(test)]', f'impl super::tests::Project for {name} {{',
                  '    fn project(&self) -> JsonNode {', '        JsonNode::object([']
        for prop in fields:
            lines += [f'            ("{prop["name"]}", self.{snake(prop["name"])}.project()),']
        lines += ['        ])', '    }', '}', '']
    return '\n'.join(lines)


def generate():
    data = SCHEMA.read_bytes()
    source = render(json.loads(data), hashlib.sha256(data).hexdigest())
    # rustfmt is a development-only dependency; builds use the committed output.
    return subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'],
                          input=source, text=True, capture_output=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = generate()
    if args.check:
        if OUTPUT.read_text() != source:
            raise SystemExit('xcresult generated.rs is out of date')
        print('xcresult generated.rs is up to date (57 objects)')
    else:
        OUTPUT.write_text(source)
        print(OUTPUT)


if __name__ == '__main__':
    main()
